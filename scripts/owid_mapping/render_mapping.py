"""Render docs/owid-mapping.md from the merged mapping.

    python -m scripts.owid_mapping.render_mapping <mapping.json> <out.md> [--focus un/2024-07-12] [--top 40]
"""
import argparse
import html
import json
import re
from pathlib import Path


def cell(text) -> str:
    return html.unescape(str(text)).replace("|", "\\|").replace("\n", " ")


def clean_title(title) -> str:
    return re.sub(r"\s*\|\s*Our World in Data\s*$", "", html.unescape(title or ""))


def render(mapping: dict, focus: str, top: int) -> str:
    groups = mapping["groups"]
    published_2026 = sum(any(d.startswith("2026") for d in g["date_published"]) for g in groups)
    crawl = mapping["crawl"]
    lines = [
        "# OWID raw data added in 2026: charts and reports that use it", "",
        f"Generated by `scripts/owid_mapping/` from OWID ETL commit `{mapping['etl_commit'][:9]}` (snapshots added since "
        f"{mapping['since']}) and a crawl of ourworldindata.org ({crawl['charts']:,} charts, {crawl['indicators']:,} "
        f"indicators, {crawl['pages']:,} pages, 2026-10-17).", "",
        "## Method", "",
        "1. **Raw data added this year**: snapshot `.dvc` files added to `snapshots/` since the cut-off "
        "(`git log --diff-filter=A`), grouped by `<namespace>/<version>`.",
        "2. **Downstream ETL steps**: transitive dependants in `dag/**/*.yml`, including `-private` steps and inline "
        "nested dependencies; grapher datasets and exports/visualisations are counted separately.",
        "3. **Charts**: each grapher chart's indicators resolve to an ETL dataset through the indicator API "
        "`catalogPath`. *Direct* charts list the group's producer and a matching dataset title among their origins; "
        "*downstream* charts also include those that use the group only for grouping or per-capita denominators.",
        "4. **Reports**: articles and topic pages that embed a direct chart; OWID data insights are counted "
        "separately; country profiles and site pages are excluded.",
        "5. **Size and dates** cover only the files added in the period. For example, `un/2024-07-12` lists 0.9 MB "
        "because only the 2026 interim update was added this year; the WPP 2024 base files date from 2024. Files "
        "added and later deleted are ignored.", "",
        "## Summary", "",
        f"- {len(groups)} snapshot groups ({sum(len(g['files']) for g in groups)} files, "
        f"{sum(g['megabytes'] for g in groups) / 1000:.1f} GB); {published_2026} published by their producer in 2026.",
        f"- {sum(1 for g in groups if g['grapher_datasets'])} groups feed at least one grapher dataset.", "",
        f"## Top {top} groups by direct charts", "",
        "| # | Group | Direct charts | Downstream charts | Reports | Reports 2026 | Data insights | Insights 2026 | "
        "Grapher datasets | Size MB | Added | Producer published | Producer | Title |",
        "|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---|---|"]
    for n, g in enumerate(groups[:top], 1):
        lines.append(f"| {n} | `{g['group']}` | {g['charts_direct']} | {g['charts_downstream']} | {g['articles']} | "
                     f"{g['articles_2026']} | {g['data_insights']} | {g['data_insights_2026']} | {len(g['grapher_datasets'])} | "
                     f"{g['megabytes']} | {g['added_to_repo']} | {cell(', '.join(g['date_published']))} | "
                     f"{cell('; '.join(g['producers']))[:60]} | {cell('; '.join(g['titles']))[:80]} |")
    group = next(g for g in groups if g["group"] == focus)
    lines += ["", f"The full table for all {len(groups)} groups is in `owid-mapping/mapping.json`.", "",
              f"## Reports using `{focus}` ({'; '.join(group['titles'])})", "",
              f"{group['articles']} articles or topic pages ({group['articles_2026']} in 2026) and {group['data_insights']} "
              f"data insights ({group['data_insights_2026']} in 2026), newest first. A report counts when it embeds at least "
              "one direct chart; for many reports WPP is only the per-capita denominator or regional grouping of another "
              "dataset, so the list overstates reports *about* population.", "",
              "| Published | Kind | Title | Direct charts |", "|---|---|---|---|"]
    for page in group["pages"]:
        kind = "article" if page["kind"] == "article" else "data insight"
        lines.append(f"| {page['published']} | {kind} | [{cell(clean_title(page['title']))}]({page['url']}) | "
                     f"{cell(', '.join(page['direct_charts']))[:160]} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("mapping", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("--focus", default="un/2024-07-12")
    parser.add_argument("--top", type=int, default=40)
    args = parser.parse_args()
    args.out.write_text(render(json.loads(args.mapping.read_text()), args.focus, args.top), encoding="utf-8")
    print(args.out)


if __name__ == "__main__":
    main()
